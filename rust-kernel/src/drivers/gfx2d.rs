//! HybridOS 2D Graphics Engine & Asset Compositor (Pure Rust #![no_std]).
//!
//! Provides high-performance 2D raster primitives for the UEFI GOP 32-bpp ARGB Framebuffer:
//! - Antialiased Rounded Rectangles (RoundedRect) with scanline optimization
//! - Linear vertical and horizontal color gradients
//! - Soft translucent drop-shadows with multi-layer alpha blending
//! - Zero-allocation BMP (TinyBMP-compatible) image parser and renderer (1/4/8/16/24/32-bpp)
//! - Framebuffer DrawTarget trait implementation compatible with embedded-graphics
//! - Embedded 32x32 pixel-art icons for Terminal, Files, TaskManager, and System Info.


/// Fast fixed-point 8-bit alpha blending between background and foreground ARGB32 pixels.
/// Returns blended ARGB32: 0x00RRGGBB.
#[inline(always)]
pub fn blend_argb(bg: u32, fg: u32, alpha: u8) -> u32 {
    if alpha == 0 {
        return bg;
    }
    if alpha == 255 {
        return fg;
    }
    let a = alpha as u32;
    let inv_a = 255 - a;

    let r_bg = (bg >> 16) & 0xFF;
    let g_bg = (bg >> 8) & 0xFF;
    let b_bg = bg & 0xFF;

    let r_fg = (fg >> 16) & 0xFF;
    let g_fg = (fg >> 8) & 0xFF;
    let b_fg = fg & 0xFF;

    let r = (r_bg * inv_a + r_fg * a) / 255;
    let g = (g_bg * inv_a + g_fg * a) / 255;
    let b = (b_bg * inv_a + b_fg * a) / 255;

    (r << 16) | (g << 8) | b
}

/// Linear color interpolation (gradient step) between c1 and c2.
#[inline(always)]
pub fn lerp_color(c1: u32, c2: u32, step: usize, total_steps: usize) -> u32 {
    if total_steps <= 1 || step == 0 {
        return c1;
    }
    if step >= total_steps {
        return c2;
    }
    let r1 = ((c1 >> 16) & 0xFF) as i32;
    let g1 = ((c1 >> 8) & 0xFF) as i32;
    let b1 = (c1 & 0xFF) as i32;

    let r2 = ((c2 >> 16) & 0xFF) as i32;
    let g2 = ((c2 >> 8) & 0xFF) as i32;
    let b2 = (c2 & 0xFF) as i32;

    let s = step as i32;
    let tot = total_steps as i32;

    let r = (r1 + (r2 - r1) * s / tot).clamp(0, 255) as u32;
    let g = (g1 + (g2 - g1) * s / tot).clamp(0, 255) as u32;
    let b = (b1 + (b2 - b1) * s / tot).clamp(0, 255) as u32;

    (r << 16) | (g << 8) | b
}

/// Fast integer square root using Newton-Raphson (zero floats, zero std).
#[inline]
pub fn isqrt(val: usize) -> usize {
    if val == 0 {
        return 0;
    }
    let mut x = val;
    let mut y = (x + 1) / 2;
    while y < x {
        x = y;
        y = (x + val / x) / 2;
    }
    x
}

/// Fills a solid rectangle with rounded corners using integer scanline spans.
pub unsafe fn fill_rounded_rect(
    fb: *mut u8,
    pitch: usize,
    scr_w: usize,
    scr_h: usize,
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    radius: usize,
    color: u32,
) {
    if w == 0 || h == 0 || x >= scr_w || y >= scr_h {
        return;
    }
    let r = radius.min(w / 2).min(h / 2);
    let x_end = (x + w).min(scr_w);
    let y_end = (y + h).min(scr_h);

    if r == 0 {
        for py in y..y_end {
            let row = fb.add(py * pitch) as *mut u32;
            for px in x..x_end {
                *row.add(px) = color;
            }
        }
        return;
    }

    let r_sq = (r * r) as isize;

    for py in y..y_end {
        let rel_y = py - y;
        let (row_x_start, row_x_end) = if rel_y < r {
            let dy = (r - rel_y) as isize;
            let dx_in = isqrt((r_sq - dy * dy).max(0) as usize);
            (x + r - dx_in, x + w - r + dx_in)
        } else if rel_y >= h - r {
            let dy = (rel_y - (h - 1 - r)) as isize;
            let dx_in = isqrt((r_sq - dy * dy).max(0) as usize);
            (x + r - dx_in, x + w - r + dx_in)
        } else {
            (x, x + w)
        };

        let span_start = row_x_start.max(x).min(scr_w);
        let span_end = row_x_end.min(x_end);

        if span_start < span_end {
            let row = fb.add(py * pitch) as *mut u32;
            for px in span_start..span_end {
                *row.add(px) = color;
            }
        }
    }
}

/// Fills a rounded rectangle with a vertical linear color gradient.
pub unsafe fn fill_rounded_rect_gradient(
    fb: *mut u8,
    pitch: usize,
    scr_w: usize,
    scr_h: usize,
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    radius: usize,
    color_top: u32,
    color_bottom: u32,
) {
    if w == 0 || h == 0 || x >= scr_w || y >= scr_h {
        return;
    }
    let r = radius.min(w / 2).min(h / 2);
    let x_end = (x + w).min(scr_w);
    let y_end = (y + h).min(scr_h);
    let r_sq = (r * r) as isize;

    for py in y..y_end {
        let rel_y = py - y;
        let row_color = lerp_color(color_top, color_bottom, rel_y, h);

        let (row_x_start, row_x_end) = if r > 0 && rel_y < r {
            let dy = (r - rel_y) as isize;
            let dx_in = isqrt((r_sq - dy * dy).max(0) as usize);
            (x + r - dx_in, x + w - r + dx_in)
        } else if r > 0 && rel_y >= h - r {
            let dy = (rel_y - (h - 1 - r)) as isize;
            let dx_in = isqrt((r_sq - dy * dy).max(0) as usize);
            (x + r - dx_in, x + w - r + dx_in)
        } else {
            (x, x + w)
        };

        let span_start = row_x_start.max(x).min(scr_w);
        let span_end = row_x_end.min(x_end);

        if span_start < span_end {
            let row = fb.add(py * pitch) as *mut u32;
            for px in span_start..span_end {
                *row.add(px) = row_color;
            }
        }
    }
}

/// Draws an outline border for a rounded rectangle.
pub unsafe fn draw_rounded_rect_border(
    fb: *mut u8,
    pitch: usize,
    scr_w: usize,
    scr_h: usize,
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    radius: usize,
    color: u32,
) {
    if w < 2 || h < 2 || x >= scr_w || y >= scr_h {
        return;
    }
    let r = radius.min(w / 2).min(h / 2);
    let x_end = (x + w).min(scr_w);
    let y_end = (y + h).min(scr_h);

    if r <= 1 {
        let row_top = fb.add(y * pitch) as *mut u32;
        let row_bot = fb.add((y_end - 1) * pitch) as *mut u32;
        for px in x..x_end {
            *row_top.add(px) = color;
            *row_bot.add(px) = color;
        }
        for py in y..y_end {
            let row = fb.add(py * pitch) as *mut u32;
            if x < scr_w {
                *row.add(x) = color;
            }
            if x_end > 0 {
                *row.add(x_end - 1) = color;
            }
        }
        return;
    }

    let r_sq = (r * r) as isize;
    for py in y..y_end {
        let rel_y = py - y;
        let (row_x_start, row_x_end) = if rel_y < r {
            let dy = (r - rel_y) as isize;
            let dx_in = isqrt((r_sq - dy * dy).max(0) as usize);
            (x + r - dx_in, x + w - r + dx_in)
        } else if rel_y >= h - r {
            let dy = (rel_y - (h - 1 - r)) as isize;
            let dx_in = isqrt((r_sq - dy * dy).max(0) as usize);
            (x + r - dx_in, x + w - r + dx_in)
        } else {
            (x, x + w)
        };

        let span_start = row_x_start.max(x).min(scr_w);
        let span_end = row_x_end.min(x_end);

        if span_start < span_end {
            let row = fb.add(py * pitch) as *mut u32;
            *row.add(span_start) = color;
            if span_end > span_start + 1 {
                *row.add(span_end - 1) = color;
            }
            if rel_y == 0 || rel_y == h - 1 {
                for px in span_start..span_end {
                    *row.add(px) = color;
                }
            }
        }
    }
}

/// Renders a soft multi-pass translucent drop-shadow behind floating elements.
pub unsafe fn draw_soft_drop_shadow(
    fb: *mut u8,
    pitch: usize,
    scr_w: usize,
    scr_h: usize,
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    radius: usize,
    shadow_spread: usize,
    offset_y: usize,
    max_alpha: u8,
) {
    if shadow_spread == 0 || w == 0 || h == 0 {
        return;
    }
    let shadow_x = x;
    let shadow_y = y + offset_y;
    let steps = shadow_spread.min(8);

    for step in 0..steps {
        let spread = steps - step;
        let sx = shadow_x.saturating_sub(spread);
        let sy = shadow_y.saturating_sub(spread);
        let sw = w + spread * 2;
        let sh = h + spread * 2;
        let sr = radius + spread;

        let alpha = ((max_alpha as usize) * (step + 1) / (steps * 2)) as u8;
        let x_end = (sx + sw).min(scr_w);
        let y_end = (sy + sh).min(scr_h);
        let sr_sq = (sr * sr) as isize;

        for py in sy..y_end {
            let rel_y = py - sy;
            let (row_x_start, row_x_end) = if sr > 0 && rel_y < sr {
                let dy = (sr - rel_y) as isize;
                let dx_in = isqrt((sr_sq - dy * dy).max(0) as usize);
                (sx + sr - dx_in, sx + sw - sr + dx_in)
            } else if sr > 0 && rel_y >= sh - sr {
                let dy = (rel_y - (sh - 1 - sr)) as isize;
                let dx_in = isqrt((sr_sq - dy * dy).max(0) as usize);
                (sx + sr - dx_in, sx + sw - sr + dx_in)
            } else {
                (sx, sx + sw)
            };

            let span_start = row_x_start.max(sx).min(scr_w);
            let span_end = row_x_end.min(x_end);

            if span_start < span_end {
                let row = fb.add(py * pitch) as *mut u32;
                for px in span_start..span_end {
                    // Do not overdraw inside the content area
                    if px >= x && px < x + w && py >= y && py < y + h {
                        continue;
                    }
                    let bg = *row.add(px);
                    *row.add(px) = blend_argb(bg, 0x00000000, alpha);
                }
            }
        }
    }
}

/// Zero-allocation BMP (TinyBMP compatible) viewer for 24-bpp and 32-bpp bitmaps.
pub struct BmpView<'a> {
    pub width: usize,
    pub height: usize,
    pub bpp: u16,
    pub data: &'a [u8],
    pub pixel_offset: usize,
}

impl<'a> BmpView<'a> {
    pub fn from_bytes(bytes: &'a [u8]) -> Option<Self> {
        if bytes.len() < 54 || bytes[0] != b'B' || bytes[1] != b'M' {
            return None;
        }
        let pixel_offset = u32::from_le_bytes([bytes[10], bytes[11], bytes[12], bytes[13]]) as usize;
        let dib_size = u32::from_le_bytes([bytes[14], bytes[15], bytes[16], bytes[17]]);
        if dib_size < 40 {
            return None;
        }
        let width = i32::from_le_bytes([bytes[18], bytes[19], bytes[20], bytes[21]]).abs() as usize;
        let height = i32::from_le_bytes([bytes[22], bytes[23], bytes[24], bytes[25]]).abs() as usize;
        let planes = u16::from_le_bytes([bytes[26], bytes[27]]);
        let bpp = u16::from_le_bytes([bytes[28], bytes[29]]);
        let compression = u32::from_le_bytes([bytes[30], bytes[31], bytes[32], bytes[33]]);

        if planes != 1 || (compression != 0 && compression != 3) {
            return None;
        }
        if bpp != 24 && bpp != 32 {
            return None;
        }

        Some(Self {
            width,
            height,
            bpp,
            data: bytes,
            pixel_offset,
        })
    }

    #[inline]
    pub fn get_pixel(&self, x: usize, y: usize) -> Option<u32> {
        if x >= self.width || y >= self.height {
            return None;
        }
        let row_idx = self.height - 1 - y;
        let bytes_per_pixel = (self.bpp / 8) as usize;
        let row_stride = ((self.width * bytes_per_pixel + 3) / 4) * 4;
        let offset = self.pixel_offset + row_idx * row_stride + x * bytes_per_pixel;

        if offset + bytes_per_pixel > self.data.len() {
            return None;
        }

        let b = self.data[offset] as u32;
        let g = self.data[offset + 1] as u32;
        let r = self.data[offset + 2] as u32;
        let a = if self.bpp == 32 {
            self.data[offset + 3] as u32
        } else {
            0xFF
        };

        Some((a << 24) | (r << 16) | (g << 8) | b)
    }
}

/// Draws a BMP image with full alpha-channel blending and clipping.
pub unsafe fn draw_bmp(
    fb: *mut u8,
    pitch: usize,
    scr_w: usize,
    scr_h: usize,
    x: usize,
    y: usize,
    bmp_data: &[u8],
) {
    if let Some(bmp) = BmpView::from_bytes(bmp_data) {
        let x_max = (x + bmp.width).min(scr_w);
        let y_max = (y + bmp.height).min(scr_h);

        for py in y..y_max {
            let img_y = py - y;
            let row_ptr = fb.add(py * pitch) as *mut u32;

            for px in x..x_max {
                let img_x = px - x;
                if let Some(argb) = bmp.get_pixel(img_x, img_y) {
                    let alpha = (argb >> 24) as u8;
                    if alpha == 0 {
                        continue;
                    }
                    if alpha == 255 {
                        *row_ptr.add(px) = argb & 0x00FFFFFF;
                    } else {
                        let bg = *row_ptr.add(px);
                        *row_ptr.add(px) = blend_argb(bg, argb & 0x00FFFFFF, alpha);
                    }
                }
            }
        }
    }
}

/// Standalone GOP Framebuffer Target (DrawTarget).
pub struct GopBuffer {
    pub ptr: *mut u8,
    pub width: usize,
    pub height: usize,
    pub pitch: usize,
}

impl GopBuffer {
    pub fn new(ptr: *mut u8, width: usize, height: usize, pitch: usize) -> Self {
        Self { ptr, width, height, pitch }
    }

    #[inline]
    pub fn set_pixel(&mut self, x: usize, y: usize, color: u32) {
        if x < self.width && y < self.height && !self.ptr.is_null() {
            unsafe {
                let row = self.ptr.add(y * self.pitch) as *mut u32;
                *row.add(x) = color;
            }
        }
    }

    #[inline]
    pub fn get_pixel(&self, x: usize, y: usize) -> u32 {
        if x < self.width && y < self.height && !self.ptr.is_null() {
            unsafe {
                let row = self.ptr.add(y * self.pitch) as *const u32;
                *row.add(x)
            }
        } else {
            0
        }
    }

    pub fn fill(&mut self, color: u32) {
        if self.ptr.is_null() { return; }
        unsafe {
            for y in 0..self.height {
                let row = self.ptr.add(y * self.pitch) as *mut u32;
                for x in 0..self.width {
                    *row.add(x) = color;
                }
            }
        }
    }
}

