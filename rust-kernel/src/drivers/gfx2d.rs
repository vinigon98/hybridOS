/// Box blur filter applied directly to a sub-rectangle of the framebuffer to simulate frosted glass.
pub unsafe fn apply_box_blur_frosted_glass(
    fb: *mut u8,
    pitch: usize,
    scr_w: usize,
    scr_h: usize,
    rx: usize,
    ry: usize,
    rw: usize,
    rh: usize,
) {
    if rx >= scr_w || ry >= scr_h || rw < 4 || rh < 4 {
        return;
    }
    let x_end = (rx + rw).min(scr_w - 1);
    let y_end = (ry + rh).min(scr_h - 1);
    let x_start = rx.max(1);
    let y_start = ry.max(1);

    // Fast 3x3 box blur sampling with stride 2 for performance
    for py in (y_start..y_end).step_by(2) {
        let row_m1 = fb.add((py - 1) * pitch) as *const u32;
        let row_0  = fb.add(py * pitch) as *mut u32;
        let row_p1 = fb.add((py + 1) * pitch) as *const u32;

        for px in (x_start..x_end).step_by(2) {
            let p00 = *row_m1.add(px - 1);
            let p01 = *row_m1.add(px);
            let p02 = *row_m1.add(px + 1);
            let p10 = *row_0.add(px - 1);
            let p11 = *row_0.add(px);
            let p12 = *row_0.add(px + 1);
            let p20 = *row_p1.add(px - 1);
            let p21 = *row_p1.add(px);
            let p22 = *row_p1.add(px + 1);

            let r = (((p00 >> 16) & 0xFF) + ((p01 >> 16) & 0xFF) + ((p02 >> 16) & 0xFF) +
                     ((p10 >> 16) & 0xFF) + ((p11 >> 16) & 0xFF) + ((p12 >> 16) & 0xFF) +
                     ((p20 >> 16) & 0xFF) + ((p21 >> 16) & 0xFF) + ((p22 >> 16) & 0xFF)) / 9;

            let g = (((p00 >> 8) & 0xFF) + ((p01 >> 8) & 0xFF) + ((p02 >> 8) & 0xFF) +
                     ((p10 >> 8) & 0xFF) + ((p11 >> 8) & 0xFF) + ((p12 >> 8) & 0xFF) +
                     ((p20 >> 8) & 0xFF) + ((p21 >> 8) & 0xFF) + ((p22 >> 8) & 0xFF)) / 9;

            let b = ((p00 & 0xFF) + (p01 & 0xFF) + (p02 & 0xFF) +
                     (p10 & 0xFF) + (p11 & 0xFF) + (p12 & 0xFF) +
                     (p20 & 0xFF) + (p21 & 0xFF) + (p22 & 0xFF)) / 9;

            let blurred = (r << 16) | (g << 8) | b;
            *row_0.add(px) = blurred;
            if px + 1 < x_end {
                *row_0.add(px + 1) = blurred;
            }
        }
    }
}

/// Renders a window frame with authentic Crystal Glass shader:
/// - Frosted background blur
/// - Sapphire blue tint (active: RGBA(22, 50, 84, 150) / inactive: RGBA(60, 75, 92, 110))
/// - Diagonal specular light streaks (12-18% alpha)
/// - 1px dark outer stroke + 1px luminous white inner chamfer
/// - 6px rounded top corners
pub unsafe fn draw_crystal_glass_window_frame(
    fb: *mut u8,
    pitch: usize,
    scr_w: usize,
    scr_h: usize,
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    active: bool,
) {
    if x >= scr_w || y >= scr_h || w < 20 || h < 20 {
        return;
    }
    let x_end = (x + w).min(scr_w);
    let y_end = (y + h).min(scr_h);

    // 1. Soft drop shadow under the window
    draw_soft_drop_shadow(fb, pitch, scr_w, scr_h, x, y, w, h, 6, 8, 4, 45);

    // 2. Base sapphire glass tint & specular reflections
    let tint_color = if active { 0x00163254 } else { 0x003C4B5C };
    let tint_alpha = if active { 150u8 } else { 110u8 };
    let streak_alpha = 36u8; // ~14% specular reflection

    let r_sq = (6 * 6) as isize;

    for py in y..y_end {
        let rel_y = py - y;
        let row_ptr = fb.add(py * pitch) as *mut u32;

        // Calculate top corner rounding (r=6)
        let (row_x_start, row_x_end) = if rel_y < 6 {
            let dy = (6 - rel_y) as isize;
            let dx_in = isqrt((r_sq - dy * dy).max(0) as usize);
            (x + 6 - dx_in, x + w - 6 + dx_in)
        } else {
            (x, x + w)
        };

        let span_start = row_x_start.max(x).min(scr_w);
        let span_end = row_x_end.min(x_end);

        for px in span_start..span_end {
            let orig = *row_ptr.add(px);

            // Apply sapphire glass tint
            let mut col = blend_argb(orig, tint_color, tint_alpha);

            // Specular reflection streaks: diagonal bands
            let streak_pattern = (px + py) % 48;
            if streak_pattern < 14 {
                col = blend_argb(col, 0x00FFFFFF, streak_alpha);
            } else if streak_pattern >= 14 && streak_pattern < 20 {
                col = blend_argb(col, 0x00FFFFFF, streak_alpha / 2);
            }

            // Top highlight gradient on titlebar (first 32px)
            if rel_y < 32 {
                let grad_alpha = ((32 - rel_y) * 2).min(70) as u8;
                col = blend_argb(col, 0x00E2E8F0, grad_alpha);
            }

            // 1px inner white chamfer at top and left
            if rel_y == 1 || (px == span_start + 1 && rel_y > 1 && rel_y < h - 2) {
                col = blend_argb(col, 0x00FFFFFF, 120);
            }

            // 1px dark outer stroke
            if rel_y == 0 || px == span_start || px + 1 == span_end || py + 1 == y_end {
                col = 0x000F172A;
            }

            *row_ptr.add(px) = col;
        }
    }
}

/// Renders the 3-button Glass Control Capsule in the top-right of a window:
/// - Convex rounded pill container
/// - Minimize [-], Maximize [□], and Close [X] in vitrified ruby red (#F0756E -> #B81D13) with hover glow
pub unsafe fn draw_glass_control_capsule(
    fb: *mut u8,
    pitch: usize,
    scr_w: usize,
    scr_h: usize,
    capsule_x: usize,
    capsule_y: usize,
    hover_close: bool,
    hover_max: bool,
    hover_min: bool,
) {
    let cap_w = 84usize;
    let cap_h = 22usize;
    if capsule_x + cap_w > scr_w || capsule_y + cap_h > scr_h {
        return;
    }

    // 1. Pill container background
    fill_rounded_rect_gradient(
        fb, pitch, scr_w, scr_h,
        capsule_x, capsule_y, cap_w, cap_h,
        4,
        0x00334155, 0x001E293B,
    );
    draw_rounded_rect_border(
        fb, pitch, scr_w, scr_h,
        capsule_x, capsule_y, cap_w, cap_h,
        4, 0x00475569,
    );

    // 2. Button segments:
    // Minimize [-]: capsule_x .. capsule_x + 26
    let min_x = capsule_x;
    if hover_min {
        fill_rounded_rect(fb, pitch, scr_w, scr_h, min_x + 1, capsule_y + 1, 26, cap_h - 2, 3, 0x00475569);
    }
    // Draw [-] glyph: horizontal line at center
    for px in (min_x + 9)..(min_x + 19) {
        let ptr = fb.add((capsule_y + 11) * pitch) as *mut u32;
        *ptr.add(px) = 0x00F8FAFC;
        let ptr2 = fb.add((capsule_y + 12) * pitch) as *mut u32;
        *ptr2.add(px) = 0x00F8FAFC;
    }

    // Maximize [□]: capsule_x + 28 .. capsule_x + 54
    let max_x = capsule_x + 28;
    if hover_max {
        fill_rounded_rect(fb, pitch, scr_w, scr_h, max_x, capsule_y + 1, 26, cap_h - 2, 3, 0x00475569);
    }
    // Draw [□] glyph: square frame 10x10
    for py in (capsule_y + 6)..(capsule_y + 16) {
        let ptr = fb.add(py * pitch) as *mut u32;
        for px in (max_x + 8)..(max_x + 18) {
            let is_edge = py == capsule_y + 6 || py == capsule_y + 15 || px == max_x + 8 || px == max_x + 17;
            if is_edge {
                *ptr.add(px) = 0x00F8FAFC;
            }
        }
    }

    // Close [X]: capsule_x + 56 .. capsule_x + 83 (Ruby Red convex gradient)
    let close_x = capsule_x + 56;
    let close_top = if hover_close { 0x00FF4B4B } else { 0x00F0756E };
    let close_bot = if hover_close { 0x00D90429 } else { 0x00B81D13 };
    fill_rounded_rect_gradient(
        fb, pitch, scr_w, scr_h,
        close_x, capsule_y + 1, 27, cap_h - 2,
        3, close_top, close_bot,
    );
    // Draw [X] glyph
    for i in 0..8 {
        let py = capsule_y + 7 + i;
        let ptr = fb.add(py * pitch) as *mut u32;
        let px1 = close_x + 9 + i;
        let px2 = close_x + 16 - i;
        *ptr.add(px1) = 0x00FFFFFF;
        *ptr.add(px1 + 1) = 0x00FFFFFF;
        *ptr.add(px2) = 0x00FFFFFF;
        *ptr.add(px2 + 1) = 0x00FFFFFF;
    }
}

/// Renders the Crystal Sphere Emblem:
/// - 44px diameter sphere extending 4px above the 40px superbar
/// - Chrome metallic outer ring
/// - Radial 3D glass sphere gradient (specular white highlight -> cyan glow -> deep sapphire)
pub unsafe fn draw_crystal_sphere_emblem(
    fb: *mut u8,
    pitch: usize,
    scr_w: usize,
    scr_h: usize,
    cx: usize,
    cy: usize,
    hovered: bool,
) {
    let radius = 22isize;
    let r_sq = radius * radius;
    let chrome_r_sq = (radius + 2) * (radius + 2);

    let x_min = (cx as isize - radius - 2).max(0) as usize;
    let x_max = ((cx as isize + radius + 3).min(scr_w as isize)) as usize;
    let y_min = (cy as isize - radius - 2).max(0) as usize;
    let y_max = ((cy as isize + radius + 3).min(scr_h as isize)) as usize;

    for py in y_min..y_max {
        let dy = py as isize - cy as isize;
        let row_ptr = fb.add(py * pitch) as *mut u32;

        for px in x_min..x_max {
            let dx = px as isize - cx as isize;
            let dist_sq = dx * dx + dy * dy;

            if dist_sq <= chrome_r_sq && dist_sq > r_sq {
                // Outer chrome metallic ring
                let chrome_color = if dy < 0 { 0x00E2E8F0 } else { 0x0094A3B8 };
                *row_ptr.add(px) = chrome_color;
            } else if dist_sq <= r_sq {
                // Sphere body with 3D radial specular highlight (light source top-left: dx=-7, dy=-7)
                let hl_dx = dx + 7;
                let hl_dy = dy + 7;
                let hl_dist = isqrt((hl_dx * hl_dx + hl_dy * hl_dy).max(0) as usize) as u32;

                let col = if hl_dist < 6 {
                    // Brilliant specular hotspot
                    0x00FFFFFF
                } else if hl_dist < 14 {
                    // Cyan glow transition
                    if hovered { 0x0067E8F9 } else { 0x0038BDF8 }
                } else if hl_dist < 22 {
                    // Deep sapphire body
                    if hovered { 0x001D4ED8 } else { 0x001E3A8A }
                } else {
                    // Dark sphere edge
                    0x000F172A
                };

                // Inner cross emblem detail
                let is_cross_h = dy.abs() <= 2 && dx.abs() <= 12;
                let is_cross_v = dx.abs() <= 2 && dy.abs() <= 12;
                let final_col = if is_cross_h || is_cross_v {
                    blend_argb(col, 0x00FFFFFF, 160)
                } else {
                    col
                };

                *row_ptr.add(px) = final_col;
            }
        }
    }
}

/// Renders the 40px Vitrified Superbar along the bottom of the screen:
/// - Dark frosted glass body: RGBA(15, 23, 42, 215)
/// - Top 1px luminous cyan accent line (0x38BDF8)
/// - Rightmost 15px "Show Desktop" peek strip with divider
pub unsafe fn draw_vitrified_superbar(
    fb: *mut u8,
    pitch: usize,
    scr_w: usize,
    scr_h: usize,
    bar_h: usize,
    peek_hover: bool,
) {
    if bar_h > scr_h {
        return;
    }
    let bar_top = scr_h - bar_h;

    // 1. Frosted superbar background
    for py in bar_top..scr_h {
        let rel_y = py - bar_top;
        let row_ptr = fb.add(py * pitch) as *mut u32;

        for px in 0..scr_w {
            let orig = *row_ptr.add(px);
            // Glass blend with dark navy tint
            let mut col = blend_argb(orig, 0x000B132B, 215);

            // Subtle horizontal specular band in upper half
            if rel_y > 1 && rel_y < 16 {
                col = blend_argb(col, 0x00FFFFFF, 25);
            }

            *row_ptr.add(px) = col;
        }
    }

    // 2. Top 1px luminous accent line
    let top_row = fb.add(bar_top * pitch) as *mut u32;
    for px in 0..scr_w {
        *top_row.add(px) = 0x0038BDF8;
    }

    // 3. Rightmost 15px "Show Desktop" Peek Strip
    let peek_x = scr_w.saturating_sub(15);
    let peek_bg = if peek_hover { 0x0038BDF8 } else { 0x001E293B };
    for py in (bar_top + 1)..scr_h {
        let row_ptr = fb.add(py * pitch) as *mut u32;
        // 1px left divider line
        *row_ptr.add(peek_x) = 0x00475569;
        for px in (peek_x + 1)..scr_w {
            *row_ptr.add(px) = blend_argb(*row_ptr.add(px), peek_bg, 140);
        }
    }
}


