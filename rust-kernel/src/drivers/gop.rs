pub struct GopConsole {
    pub fb_ptr: *mut u8,
    pub width: usize,
    pub height: usize,
    pub pitch: usize,
    pub cursor_col: usize,
    pub cursor_row: usize,
    pub max_cols: usize,
    pub max_rows: usize,
    pub fg_color: u32,
    pub bg_color: u32,
}

unsafe impl Send for GopConsole {}
unsafe impl Sync for GopConsole {}

pub static GOP_CONSOLE: SpinLock<Option<GopConsole>> = SpinLock::new(None);

impl GopConsole {
    pub fn new(fb_ptr: *mut u8, width: usize, height: usize, pitch: usize) -> Self {
        let max_cols = width / 8;
        let max_rows = height / 16;

        Self {
            fb_ptr,
            width,
            height,
            pitch,
            cursor_col: 0,
            cursor_row: 2,
            max_cols,
            max_rows,
            fg_color: 0x00E2E8F0, // Bright Slate Gray
            bg_color: 0x000F172A, // Deep Navy
        }
    }

    /// Draws the persistent HybridOS GUI Top Status Header Bar (Rows 0..1)
    pub fn draw_header_bar(&mut self) {
        if self.fb_ptr.is_null() || self.height < 32 {
            return;
        }
        let header_bg: u32 = 0x001E293B; // Slate 800
        let accent_line: u32 = 0x0038BDF8; // Sky Blue 400

        unsafe {
            for y in 0..30 {
                let row_ptr = self.fb_ptr.add(y * self.pitch) as *mut u32;
                for x in 0..self.width {
                    *row_ptr.add(x) = header_bg;
                }
            }
            for y in 30..32 {
                let row_ptr = self.fb_ptr.add(y * self.pitch) as *mut u32;
                for x in 0..self.width {
                    *row_ptr.add(x) = accent_line;
                }
            }
        }

        let saved_fg = self.fg_color;
        let saved_bg = self.bg_color;
        self.fg_color = 0x0038BDF8;
        self.bg_color = header_bg;

        let title = " [HybridOS x86_64 GUI Console] | Ring-0 Bare-Metal | Dual-ABI: Windows NT (PE64) + Linux (ELF64) ";
        for (idx, ch) in title.chars().enumerate() {
            if idx < self.max_cols {
                self.draw_char(idx, 0, ch);
            }
        }

        self.fg_color = saved_fg;
        self.bg_color = saved_bg;
    }

    /// Clear entire display with background color and redraw header bar
    pub fn clear(&mut self) {
        if self.fb_ptr.is_null() {
            return;
        }
        unsafe {
            for y in 0..self.height {
                let row_ptr = self.fb_ptr.add(y * self.pitch) as *mut u32;
                for x in 0..self.width {
                    *row_ptr.add(x) = self.bg_color;
                }
            }
        }
        self.draw_header_bar();
        self.cursor_col = 0;
        self.cursor_row = 2;
    }

    /// Plots an 8x16 character at (col, row)
    pub fn draw_char(&mut self, col: usize, row: usize, c: char) {
        if self.fb_ptr.is_null() || col >= self.max_cols || row >= self.max_rows {
            return;
        }

        let code = c as u32;
        let ascii_val = if code >= 32 && code <= 127 {
            code as usize
        } else {
            b'?' as usize
        };
        let font_idx = (ascii_val - 32) * 16;
        let start_x = col * 8;
        let start_y = row * 16;

        unsafe {
            for y in 0..16 {
                let glyph_byte = FONT_8X16[font_idx + y];
                let row_ptr = self.fb_ptr.add((start_y + y) * self.pitch) as *mut u32;
                for x in 0..8 {
                    let is_lit = (glyph_byte & (0x80 >> x)) != 0;
                    let color = if is_lit { self.fg_color } else { self.bg_color };
                    *row_ptr.add(start_x + x) = color;
                }
            }
        }
    }

    /// Scrolls console viewport (from row 2 downwards) up by 1 text line (16 pixel rows)
    pub fn scroll_up(&mut self) {
        if self.fb_ptr.is_null() || self.height <= 48 {
            return;
        }

        let top_px = 32; // Preserve 32px header bar (rows 0 and 1)
        unsafe {
            let bytes_to_copy = (self.height - top_px - 16) * self.pitch;
            let src = self.fb_ptr.add((top_px + 16) * self.pitch);
            let dest = self.fb_ptr.add(top_px * self.pitch);
            core::ptr::copy(src, dest, bytes_to_copy);

            // Blank bottom line
            for y in (self.height - 16)..self.height {
                let row_ptr = self.fb_ptr.add(y * self.pitch) as *mut u32;
                for x in 0..self.width {
                    *row_ptr.add(x) = self.bg_color;
                }
            }
        }

        if self.cursor_row > 2 {
            self.cursor_row -= 1;
        }
    }

    /// Prints a single character handling newlines and word wrapping
    pub fn put_char(&mut self, c: char) {
        match c {
            '\n' => {
                self.cursor_col = 0;
                self.cursor_row += 1;
                if self.cursor_row >= self.max_rows {
                    self.scroll_up();
                }
            }
            '\r' => {
                self.cursor_col = 0;
            }
            '\t' => {
                self.cursor_col = (self.cursor_col + 4) & !3;
                if self.cursor_col >= self.max_cols {
                    self.put_char('\n');
                }
            }
            '\x08' => {
                if self.cursor_col > 0 {
                    self.cursor_col -= 1;
                    let (c, r) = (self.cursor_col, self.cursor_row);
                    self.draw_char(c, r, ' ');
                }
            }
            printable => {
                let (c, r) = (self.cursor_col, self.cursor_row);
                self.draw_char(c, r, printable);
                self.cursor_col += 1;
                if self.cursor_col >= self.max_cols {
                    self.cursor_col = 0;
                    self.cursor_row += 1;
                    if self.cursor_row >= self.max_rows {
                        self.scroll_up();
                    }
                }
            }
        }
    }

    /// Prints a string slice to the GOP console (supports ANSI clear screen escape)
    pub fn write_str(&mut self, s: &str) {
        if s.contains("\x1B[2J") {
            self.clear();
            return;
        }
        for c in s.chars() {
            self.put_char(c);
        }
    }
}

/// Initializes the GOP Framebuffer console using the Limine framebuffer response
pub fn init_gop_console() {
    if let Some((fb_slice, width, height, pitch)) = crate::boot::get_framebuffer() {
        let mut console = GopConsole::new(fb_slice.as_mut_ptr(), width as usize, height as usize, pitch as usize);
        console.clear();
        console.write_str("================================================================\n");
        console.write_str(" HybridOS x86_64 Bare-Metal Kernel Console (UEFI GOP Framebuffer)\n");
        console.write_str(" Dual-Personality Native Subsystem (Linux POSIX + Windows NT)\n");
        console.write_str("================================================================\n\n");
        *GOP_CONSOLE.lock() = Some(console);
        crate::serial_println!("[GOP CONSOLE] Framebuffer Text Console online ({}x{} pixels, {}x{} chars).", width, height, width / 8, height / 16);
    }
}

/// Helper function to write to GOP console from serial print macros
pub fn gop_print(text: &str) {
    if let Some(ref mut con) = *GOP_CONSOLE.lock() {
        con.write_str(text);
    }
}
